from pathlib import Path
Path('obscured_quasar').mkdir(exist_ok = True)
for id, ra, dec in zip(id_list[1:], ra_list[1:], dec_list[1:]):
    result = gwconnector.query(ra = ra, dec = dec)
    print(f'ID: {id}, RA: {ra}, DEC: {dec}, Result: {len(result)}')
    if len(result) > 0:
        # Write catalogs
        import shutil
        for filepath in result['filepath']:
            catalog_file = Path(filepath).parent / 'phot' / Path(filepath).with_suffix('.phot.cat').name
            if catalog_file.exists():
                # copy to obscured_quasar/id/id_catalog.phot.cat
                (Path('obscured_quasar') / f'{id}').mkdir(exist_ok = True)
                shutil.copy(catalog_file, Path('obscured_quasar') / f'{id}' /  Path(filepath).with_suffix('.phot.cat').name)
                
        result.remove_columns(['footprint', 'footprint_galactic', 'filepath', 'catalog_filepath'])
        result.write(Path('obscured_quasar') / f'{id}_metadata.ascii', format = 'ascii')
        print(f'Saved {id}_metadata.ascii')
